/**
 * Contract between the API and the app. The real answers of the API (and the bodies the
 * app sends, in `requests.json`) live in `frontend/src/__tests__/contract/fixtures`:
 *
 * - Here the API answers are compared with the committed fixtures: change a field in a
 *   presenter or a zod response schema and this test fails until the fixtures are
 *   regenerated (`UPDATE_CONTRACT=1 npx jest contract`).
 * - The frontend test type-checks the same fixtures against its types, both ways, so a
 *   field added, removed or renamed on one side breaks the other side's build.
 * - The bodies the app sends are replayed here against the real routes (zod included).
 */
import { spawnSync } from 'child_process';
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { resolve } from 'path';
import request from 'supertest';
import { totpCode } from '@domain/services/totp';
import { TestContext, TestUser, createTestApp, createUser } from '../helpers/testApp';

const DIR = resolve(__dirname, '../../../../frontend/src/__tests__/contract/fixtures');
interface Call {
  name: string;
  method: string;
  path: string;
  auth: boolean;
  body: unknown;
}
/** What the app sends, captured by frontend/src/__tests__/contract/requests.test.ts. */
const requests = JSON.parse(readFileSync(resolve(DIR, 'requests.json'), 'utf8')) as Call[];
const UPDATE = !!process.env.UPDATE_CONTRACT;
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const JWT = /^eyJ[\w-]+\.[\w-]+\.[\w-]+$/;

/** Random values (ids, tokens, secrets) become stable, keeping which ones are the same. */
function stabilise(value: unknown, ids: Map<string, string>): unknown {
  if (Array.isArray(value)) return value.map((v) => stabilise(v, ids));
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, stabilise(v, ids)]));
  }
  if (typeof value !== 'string') return value;
  if (JWT.test(value)) return 'jwt.token.value';
  if (UUID.test(value)) {
    if (!ids.has(value)) {
      ids.set(value, `00000000-0000-4000-8000-${String(ids.size + 1).padStart(12, '0')}`);
    }
    return ids.get(value);
  }
  return value;
}

const HEADER =
  '// Generated by backend/src/tests/integration/contract.test.ts (UPDATE_CONTRACT=1). Do not edit.';

/** The answer with the random values (ids, tokens, secrets) made stable. */
function stable(body: unknown, mask: Record<string, string>): unknown {
  const masked = (v: unknown): unknown => {
    if (Array.isArray(v)) return v.map(masked);
    if (v && typeof v === 'object') {
      return Object.fromEntries(
        Object.entries(v).map(([k, x]) => [k, k in mask ? mask[k] : masked(x)])
      );
    }
    return v;
  };
  return masked(stabilise(body, new Map()));
}

/** Prettier 3 does not run inside Jest (CommonJS): the command line formats the new file. */
function format(source: string, file: string): string {
  const cli = require.resolve('prettier/bin/prettier.cjs');
  const out = spawnSync(process.execPath, [cli, '--stdin-filepath', file], { input: source });
  if (out.status !== 0) throw new Error(`prettier failed: ${out.stderr}`);
  return out.stdout.toString();
}

/** The value a fixture file holds (`export const name = {...} as const;`). */
function readFixture(name: string): unknown {
  const file = resolve(DIR, `${name}.ts`);
  if (!existsSync(file)) return '(missing: run UPDATE_CONTRACT=1 npx jest contract)';
  const source = readFileSync(file, 'utf8');
  const start = source.indexOf(`export const ${name} = `) + `export const ${name} = `.length;
  const end = source.lastIndexOf(' as const;');
  // A plain object literal written by this test: evaluated, not parsed, as it is not JSON.
  return new Function(`return (${source.slice(start, end)})`)();
}

/**
 * Checks (or, with UPDATE_CONTRACT, writes) the fixture of an API answer. A field that moved
 * shows in the diff, and the frontend test type-checks the fixture against the app types.
 */
function contract(name: string, body: unknown, mask: Record<string, string> = {}): void {
  const value = stable(body, mask);
  if (UPDATE) {
    const file = resolve(DIR, `${name}.ts`);
    const source = `${HEADER}\nexport const ${name} = ${JSON.stringify(value)} as const;\n`;
    writeFileSync(file, format(source, file));
    return;
  }
  expect({ fixture: name, value: readFixture(name) }).toEqual({ fixture: name, value });
}

/** Fills `{totp}`, `{category:Ocio}`… in a path or body of `requests.json`. */
function fill(value: unknown, vars: Record<string, string>): unknown {
  if (Array.isArray(value)) return value.map((v) => fill(v, vars));
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, fill(v, vars)]));
  }
  if (typeof value !== 'string') return value;
  return value.replace(/\{([\w:]+)\}/g, (all, key: string) => {
    if (!(key in vars)) throw new Error(`The request fixture uses ${all}, which the test lacks`);
    return vars[key];
  });
}

/** Sends one of the requests the app builds (an unknown name is a test bug). */
function replay(
  ctx: TestContext,
  name: string,
  user: TestUser | null,
  vars: Record<string, string> = {}
): request.Test {
  const call = requests.find((r) => r.name === name);
  if (!call) throw new Error(`No request fixture called ${name}`);
  const agent = request(ctx.app) as unknown as Record<string, (url: string) => request.Test>;
  let test = agent[call.method.toLowerCase()](`/api${fill(call.path, vars)}`);
  if (call.auth && user) test = test.set(user.auth);
  return call.body === null ? test : test.send(fill(call.body, vars) as object);
}

const OK = [200, 201, 204];
/** Fails with the answer of the API when it does not accept the request. */
async function accepted(test: request.Test): Promise<request.Response> {
  const res = await test;
  if (!OK.includes(res.status)) throw new Error(`${res.status} ${JSON.stringify(res.body)}`);
  return res;
}

describe('API contract', () => {
  let ctx: TestContext;
  let user: TestUser;
  const get = (path: string) => request(ctx.app).get(`/api${path}`).set(user.auth).expect(200);
  const send = (name: string, vars: Record<string, string> = {}) =>
    accepted(replay(ctx, name, user, vars));

  beforeEach(async () => {
    ctx = createTestApp({ now: '2026-03-15T12:00:00Z' });
    user = await createUser(ctx, 'ana@example.com');
  });

  async function categoryId(name: string): Promise<string> {
    const list = (await get('/categories')).body as { id: string; name: string }[];
    return list.find((c) => c.name === name)!.id;
  }
  const vars = async () => ({
    'category:Ocio': await categoryId('Ocio'),
    'category:Salario': await categoryId('Salario'),
  });

  describe('answers (compared with the fixtures the app type-checks)', () => {
    it('months and movements', async () => {
      const created = await send('transactionCreate', await vars());
      await request(ctx.app)
        .post('/api/transactions')
        .set(user.auth)
        .send({
          description: 'Nómina',
          type: 'INCOME',
          category: 'Salario',
          amount: 2000,
          date: '2026-03-01',
        })
        .expect(201);
      await send('budgetSet', await vars());
      contract('transaction', created.body);
      contract('monthOverview', (await get('/months/2026/3')).body);
      contract('annualSummary', (await get('/transactions/annual/2026')).body);
      contract(
        'transactionSearch',
        (await get('/transactions/search?q=Cena&limit=10&sort=date_desc')).body
      );
      contract('categories', (await get('/categories')).body);
      contract('budgets', (await get('/budgets')).body);
      contract('settings', (await get('/settings')).body);
    });

    it('accounts, goals and imports', async () => {
      await send('accountCreate');
      contract('accounts', (await get('/accounts')).body);
      await send('goalCreate');
      contract('goals', (await get('/goals')).body);
      contract('importResult', (await send('importPreview')).body);
    });

    it('plan, catalog and referral', async () => {
      contract('billingOverview', (await get('/billing')).body);
      contract('planCatalog', (await request(ctx.app).get('/api/billing/plans').expect(200)).body);
      contract('referralSummary', (await get('/referral')).body, { code: 'ABCD2345' });
    });

    it('profile and sign-in', async () => {
      const login = await accepted(replay(ctx, 'login', null));
      contract('authResult', login.body, { refreshToken: 'refresh-token' });
      contract('nameChange', (await send('profileName')).body);
      contract('avatarChange', (await send('profileAvatar')).body);
    });

    it('two-step verification', async () => {
      contract('twoFactorStatus', (await get('/auth/2fa')).body);
      const setup = (await send('twoFactorSetup')).body;
      contract('twoFactorSetup', setup, {
        secret: 'BASE32SECRET',
        otpauthUri: 'otpauth://totp',
      });
      const totp = () => totpCode(setup.secret, ctx.clock.now().getTime());
      const next = () => ctx.clock.set(new Date(ctx.clock.now().getTime() + 30_000).toISOString());
      const enabled = await send('twoFactorEnable', { totp: totp() });
      contract('twoFactorEnabled', {
        recoveryCodes: enabled.body.recoveryCodes.map(() => 'code'),
      });
      contract('twoFactorStatusOn', (await get('/auth/2fa')).body);
      next();
      const challenge = await accepted(replay(ctx, 'login', null));
      contract('twoFactorChallenge', challenge.body, { challengeToken: 'challenge' });
      const verified = await accepted(
        replay(ctx, 'twoFactorVerify', null, {
          challenge: challenge.body.challengeToken,
          totp: totp(),
        })
      );
      expect(verified.body.user.email).toBe('ana@example.com');
    });

    it('self-employed: account copy, taxes and draft', async () => {
      await send('businessSetCategory', await vars());
      await request(ctx.app)
        .post('/api/transactions')
        .set(user.auth)
        .send({
          description: 'Factura',
          type: 'INCOME',
          category: 'Salario',
          amount: 1210,
          date: '2026-02-10',
        })
        .expect(201);
      expect((await get('/business/data')).body).toBeNull();
      await send('autonomoSaveEmpty');
      contract('autonomoSaved', (await send('autonomoSaveTyped')).body);
      contract('autonomoData', (await get('/business/data')).body);
      contract('businessCategories', (await get('/business/categories')).body);
      contract('yearTax', (await get('/business/tax/2026')).body);
      contract('autonomoDraft', (await send('autonomoDraftTyped')).body);
    });
  });

  describe('crypto console (play money)', () => {
    // Made-up candles: the price goes down to the pending purchase of 40.000 € a minute later.
    const candles = [
      {
        time: Date.parse('2026-03-15T12:00:00Z'),
        open: 50_000,
        high: 50_500,
        low: 49_800,
        close: 50_100,
        volume: 2,
      },
      {
        time: Date.parse('2026-03-15T12:01:00Z'),
        open: 41_000,
        high: 41_000,
        low: 39_500,
        close: 40_500,
        volume: 3,
      },
    ];

    it('answers (compared with the fixtures the app type-checks)', async () => {
      ctx.market.setCandles('ETH', candles);
      contract('cryptoCoins', (await get('/crypto/coins')).body);
      contract('cryptoCandles', (await get('/crypto/candles?symbol=ETH&interval=1h')).body);
      const position = (await send('cryptoBuyMarket')).body.open[0].id as string;
      await send('cryptoSellLimit', { position });
      await send('cryptoBuyMarket');
      const second = (await get('/crypto/sim')).body.open.find(
        (p: { id: string }) => p.id !== position
      ).id as string;
      await send('cryptoSellMarket', { position: second });
      await send('cryptoBuyLimit');
      contract('cryptoSim', (await get('/crypto/sim')).body);
      ctx.market.setCandles('BTC', candles);
      ctx.clock.set('2026-03-15T12:05:00Z');
      contract('cryptoSimFilled', (await get('/crypto/sim')).body);
      await request(ctx.app)
        .put('/api/crypto/ranking/settings')
        .set(user.auth)
        .send({ optIn: true, alias: 'Lince' })
        .expect(200);
      contract('cryptoRanking', (await get('/crypto/ranking')).body);
      await request(ctx.app)
        .post('/api/crypto/alerts')
        .set(user.auth)
        .send({ symbol: 'BTC', condition: 'above', price: 60_000 })
        .expect(201);
      contract('cryptoAlerts', (await get('/crypto/alerts')).body);
      contract('cryptoReport', (await get('/crypto/seasons/2026-03/report')).body);
    });

    it('requests (the bodies the app sends are accepted by the routes)', async () => {
      const position = (await send('cryptoBuyMarket')).body.open[0].id as string;
      for (const name of [
        'cryptoBuyWithExits',
        'cryptoShort',
        'cryptoSellLimit',
        'cryptoSellMarket',
        'cryptoBuyLimit',
      ]) {
        await send(name, { position });
      }
      const practice = (await send('cryptoPractice')).body.portfolio.id as string;
      for (const name of ['cryptoBuyPractice', 'cryptoResetPractice', 'cryptoDeletePractice']) {
        await send(name, { practice });
      }
      await send('cryptoRanking');
      const alert = (await send('cryptoAlert')).body.alerts[0].id as string;
      await send('cryptoDeleteAlert', { alert });
    });
  });

  describe('requests (the bodies the app sends are accepted by the routes)', () => {
    it('sign-up, sign-in and profile', async () => {
      await accepted(replay(ctx, 'register', null));
      await accepted(replay(ctx, 'registerCreator', null));
      await accepted(replay(ctx, 'login', null));
      await send('profileName');
      await send('profileAvatar');
    });

    it('two-step verification, from set-up to turning it off', async () => {
      const setup = (await send('twoFactorSetup')).body;
      const totp = () => totpCode(setup.secret, ctx.clock.now().getTime());
      const next = () => ctx.clock.set(new Date(ctx.clock.now().getTime() + 30_000).toISOString());
      await send('twoFactorEnable', { totp: totp() });
      next();
      await send('twoFactorRecoveryCodes', { totp: totp() });
      await send('twoFactorDisable');
    });

    it('movements, imports and everything around them', async () => {
      const v = await vars();
      const { body } = await send('transactionCreate', v);
      const ids = { transaction: body.id as string };
      for (const name of [
        'transactionUpdate',
        'transactionNotes',
        'transactionBulkUpdate',
        'importPreview',
        'importCommit',
        'categoryCreate',
        'accountCreate',
        'budgetSet',
        'goalCreate',
        'recurringCreate',
        'customAlertCreate',
        'settingsUpdate',
        'transactionBulkDelete',
      ]) {
        await send(name, { ...v, ...ids });
      }
    });

    it('self-employed, plans and payments', async () => {
      const v = await vars();
      for (const name of [
        'businessSetCategory',
        'autonomoSaveEmpty',
        'autonomoSaveTyped',
        'autonomoSaveFiled',
        'autonomoDraftEmpty',
        'autonomoDraftTyped',
        'autonomoDraftFiled',
        'checkoutMonthly',
        'checkoutRentaPass',
        'rentaCalculation',
      ]) {
        await send(name, v);
      }
    });

    it('every request fixture is replayed by one of the tests above', () => {
      const used = readFileSync(__filename, 'utf8');
      const unused = requests.filter((r) => !used.includes(`'${r.name}'`)).map((r) => r.name);
      expect(unused).toEqual([]);
    });
  });
});
